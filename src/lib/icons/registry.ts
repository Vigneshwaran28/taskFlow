/** Fast ID-based lookup for all catalog items */
export const ICON_BY_ID = Object.freeze(
  Object.fromEntries(ICON_CATALOG.map((item) => [item.id, item])) as Record<string, IconItem>
);

/**
 * Resolves the appropriate Icon component for a navigation or module key.
 * 1. Checks if the user assigned a custom icon override (e.g. customIcons["sales"] === "material:sales")
 * 2. Otherwise returns the corresponding icon from the user's active icon library
 * 3. Falls back to fallbackComponent or Lucide default
 */
export function resolveNavIcon(
  navKey: NavIconKey | string,
  library: IconLibraryKey = "lucide",
  customIcons?: Record<string, string> | null,
  fallbackComponent?: IconComponent
): IconComponent {
  // 1. Check custom override
  if (customIcons && customIcons[navKey]) {
    const customId = customIcons[navKey];
    if (ICON_BY_ID[customId]) {
      return ICON_BY_ID[customId].component;
    }
  }

  // 2. Resolve from active library
  const libIcons = NAV_ICONS[library] || NAV_ICONS.lucide;
  const match = (libIcons as Record<string, IconComponent>)[navKey];
  if (match) return match;

  // 3. Fallback
  return fallbackComponent || (NAV_ICONS.lucide as Record<string, IconComponent>)[navKey] || LuLayoutDashboard;
}
